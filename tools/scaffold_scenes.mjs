#!/usr/bin/env node
// Director's hand-off step. Reads runs/<id>/direction.json and:
//  1. copies every asset the scenes need into studio/public/runs/<id>/
//  2. writes runs/<id>/scenes/<SID>/props.json (duration from VO length + padding)
//  3. creates a stub studio/src/scenes/<runKey>/<SID>.tsx for each scene (never overwrites)
//  4. regenerates studio/src/scenes/registry.ts
// Usage: node tools/scaffold_scenes.mjs runs/<id>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const runDir = path.resolve(ROOT, process.argv[2] ?? "");
const runId = path.basename(runDir);
const direction = JSON.parse(fs.readFileSync(path.join(runDir, "direction.json"), "utf8"));
const fps = direction.fps ?? 30;
const runKey = "r_" + runId.replace(/[^a-zA-Z0-9]/g, "_");
const pub = path.join(ROOT, "studio", "public", "runs", runId);
fs.mkdirSync(pub, { recursive: true });

const copyAsset = (rel) => {
  const src = path.resolve(ROOT, rel);
  if (!fs.existsSync(src)) {
    console.warn(`  ! missing asset: ${rel}`);
    return null;
  }
  const dest = path.join(pub, path.basename(rel));
  fs.copyFileSync(src, dest);
  return `runs/${runId}/${path.basename(rel)}`; // staticFile() path
};

const sceneDir = path.join(ROOT, "studio", "src", "scenes", runKey);
fs.mkdirSync(sceneDir, { recursive: true });
const template = fs.readFileSync(path.join(ROOT, "studio", "templates", "scene.tsx"), "utf8");

const registry = [];
for (const s of direction.scenes) {
  let vo = null;
  let voDur = 0;
  if (s.vo?.file) {
    const wordsPath = path.resolve(ROOT, s.vo.words ?? s.vo.file.replace(/\.mp3$/, ".words.json"));
    const w = fs.existsSync(wordsPath) ? JSON.parse(fs.readFileSync(wordsPath, "utf8")) : { words: [], durationSec: 0 };
    voDur = w.durationSec ?? 0;
    vo = { src: copyAsset(s.vo.file), words: w.words ?? [] };
  }
  const baseSec = s.durationSec ?? voDur + (s.padSec ?? 0.25);
  const durationInFrames = Math.max(15, Math.ceil(baseSec * fps));
  const assets = {};
  for (const a of s.assets ?? []) {
    const key = typeof a === "string" ? path.basename(a).replace(/\.[^.]+$/, "") : a.key;
    const rel = typeof a === "string" ? a : a.file;
    assets[key] = copyAsset(rel);
  }
  const sfx = (s.sfx ?? []).map((c) => ({ src: copyAsset(c.file), atSec: c.atSec ?? 0, volume: c.volume ?? 0.6 }));
  const props = {
    runId,
    sceneId: s.id,
    durationInFrames,
    vo,
    sfx: sfx.filter((c) => c.src),
    assets,
    onScreenText: s.onScreenText ?? "",
    accentWords: s.accentWords ?? [],
    showCaptions: s.showCaptions ?? true,
    captionStyle: s.captionStyle ?? "phrase",
    captionKeywords: s.captionKeywords ?? [],
    captionEmoji: s.captionEmoji ?? {},
  };
  const propsDir = path.join(runDir, "scenes", s.id);
  fs.mkdirSync(propsDir, { recursive: true });
  fs.writeFileSync(path.join(propsDir, "props.json"), JSON.stringify(props, null, 2));

  const file = path.join(sceneDir, `${s.id}.tsx`);
  if (!fs.existsSync(file)) fs.writeFileSync(file, template.replaceAll("__SCENE__", `${runId} ${s.id}`));
  registry.push({ id: `${runId}-${s.id}`.replace(/[^a-zA-Z0-9-]/g, "-"), imp: `./${runKey}/${s.id}`, name: `${runKey}_${s.id}` });
  console.log(`  ${s.id}: ${(durationInFrames / fps).toFixed(2)}s  -> composition ${registry.at(-1).id}`);
}

const lines = [
  "// AUTO-GENERATED by tools/scaffold_scenes.mjs — the director regenerates this per run.",
  "// Composer agents edit only their own scene file, never this registry.",
  'import type React from "react";',
  'import Demo_S01 from "./_demo/S01";',
  ...registry.map((r) => `import ${r.name} from "${r.imp}";`),
  "",
  "export const scenes: { id: string; component: React.FC<any> }[] = [",
  '  { id: "demo-S01", component: Demo_S01 },',
  ...registry.map((r) => `  { id: "${r.id}", component: ${r.name} },`),
  "];",
  "",
];
fs.writeFileSync(path.join(ROOT, "studio", "src", "scenes", "registry.ts"), lines.join("\n"));
fs.writeFileSync(
  path.join(runDir, "scenes", "index.json"),
  JSON.stringify(registry.map((r, i) => ({ sceneId: direction.scenes[i].id, composition: r.id, file: `studio/src/scenes/${r.imp.slice(2)}.tsx` })), null, 2),
);
console.log(`Scaffolded ${registry.length} scenes for ${runId}`);
